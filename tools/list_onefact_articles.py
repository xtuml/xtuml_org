#!/usr/bin/env python3
"""Write a Jekyll data file listing One Fact blog posts that are not already on xtuml.org.

Reads the _articles collection from a checkout of github.com/xtuml/onefactinc.
Each kept post becomes a title, date, description, and https://onefact.net link.
Posts already published in this site's articles/ folder are omitted, matched by
title or slug. The result is build output at _data/onefact_articles.yml.

Usage:
  python3 tools/list_onefact_articles.py /path/to/onefactinc
  python3 tools/list_onefact_articles.py /path/to/onefactinc/_articles
"""

import argparse
import re
import sys
from pathlib import Path

SITE = "https://onefact.net"
ROOT = Path(__file__).resolve().parents[1]


def unquote(value):
    if value in ("true", "True"):
        return True
    if value in ("false", "False"):
        return False
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1].replace('\\"', '"').replace("\\'", "'")
    return value


def front_matter(text):
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    data = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if not line.strip() or line.lstrip().startswith("#") or ":" not in line:
            continue
        key, value = line.split(":", 1)
        data[key.strip()] = unquote(value.strip())
    return data


def norm_title(title):
    text = title.casefold()
    text = text.replace("–", "-").replace("—", "-").replace("−", "-")
    text = re.sub(r"[^0-9a-z]+", " ", text)
    return " ".join(text.split())


def norm_slug(slug):
    slug = slug.strip().strip("/").casefold()
    slug = re.sub(r"-\d+$", "", slug)
    return slug


def slug_of(path, permalink):
    if permalink:
        return permalink.strip().strip("/")
    return path.stem


def load_local_articles(articles_dir):
    titles = set()
    slugs = set()
    for path in articles_dir.glob("*"):
        if path.suffix.lower() not in (".md", ".html", ".markdown") or not path.is_file():
            continue
        meta = front_matter(path.read_text(encoding="utf-8"))
        title = meta.get("title") or ""
        if title:
            titles.add(norm_title(str(title)))
        permalink = str(meta.get("permalink") or "")
        slugs.add(norm_slug(slug_of(path, permalink)))
    return titles, slugs


def public_url(permalink, path):
    slug = slug_of(path, str(permalink or ""))
    return f"{SITE}/{slug}/"


def yaml_quote(value):
    text = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{text}"'


def collect(articles_dir, local_titles, local_slugs):
    dated = []
    undated = []
    skipped = []
    paths = [
        path
        for path in articles_dir.iterdir()
        if path.is_file() and path.suffix.lower() in (".md", ".html", ".markdown")
    ]
    for path in sorted(paths, key=lambda item: item.name):
        meta = front_matter(path.read_text(encoding="utf-8"))
        title = str(meta.get("title") or "").strip()
        if not title:
            continue
        slug = norm_slug(slug_of(path, str(meta.get("permalink") or "")))
        if norm_title(title) in local_titles or slug in local_slugs:
            skipped.append(title)
            continue
        entry = {
            "title": title,
            "url": public_url(meta.get("permalink"), path),
        }
        description = str(meta.get("description") or "").strip()
        if description:
            entry["description"] = description
        raw_date = str(meta.get("date") or "").strip()
        date_match = re.match(r"(\d{4}-\d{2}-\d{2})", raw_date)
        archival = meta.get("archival_date_unknown") is True
        if date_match and not archival:
            entry["date"] = date_match.group(1)
            dated.append(entry)
        else:
            undated.append(entry)
    dated.sort(key=lambda item: item["date"], reverse=True)
    undated.sort(key=lambda item: item["title"].casefold())
    return dated, undated, skipped


def render(dated, undated):
    lines = [
        "# Generated by tools/list_onefact_articles.py. Do not edit.",
        "dated:",
    ]
    if not dated:
        lines.append("  []")
    for entry in dated:
        lines.append(f"  - title: {yaml_quote(entry['title'])}")
        lines.append(f"    date: {entry['date']}")
        if "description" in entry:
            lines.append(f"    description: {yaml_quote(entry['description'])}")
        lines.append(f"    url: {yaml_quote(entry['url'])}")
    lines.append("undated:")
    if not undated:
        lines.append("  []")
    for entry in undated:
        lines.append(f"  - title: {yaml_quote(entry['title'])}")
        if "description" in entry:
            lines.append(f"    description: {yaml_quote(entry['description'])}")
        lines.append(f"    url: {yaml_quote(entry['url'])}")
    lines.append("")
    return "\n".join(lines)


def articles_source(onefact):
    path = Path(onefact).expanduser().resolve()
    if path.name == "_articles" and path.is_dir():
        return path
    nested = path / "_articles"
    if nested.is_dir():
        return nested
    raise SystemExit(f"No _articles directory in {path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "onefact",
        help="checkout of xtuml/onefactinc, or its _articles directory",
    )
    parser.add_argument(
        "--articles",
        type=Path,
        default=ROOT / "articles",
        help="xtuml.org articles directory used to skip duplicates",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "_data" / "onefact_articles.yml",
        help="Jekyll data file to write",
    )
    args = parser.parse_args()
    source = articles_source(args.onefact)
    local_titles, local_slugs = load_local_articles(args.articles.resolve())
    dated, undated, skipped = collect(source, local_titles, local_slugs)
    output = args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(dated, undated), encoding="utf-8")
    print(
        f"Wrote {output}: {len(dated)} dated, {len(undated)} undated, {len(skipped)} skipped"
    )
    for title in skipped:
        print(f"skipped: {title}", file=sys.stderr)


if __name__ == "__main__":
    main()
